import { existsSync, readFileSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { IN } from './sandbox'
import type { CodexSetup, SetupFile } from './setup-copy'

/**
 * The human's Codex setup, as a Codex worker's sandbox gets it at its start and
 * at a wake after it changed (interactive-workers decisions 8 and 12, as `claudeSetup` does for
 * Claude Code): their instructions file, skills, prompts and rules, the parts of
 * `config.toml` that are not host-specific, their MCP servers with the logins
 * Codex keeps in a file, and their Codex login. Never hooks (they run host-path
 * scripts), history, logs or the host's own rollouts.
 *
 * The worker's `config.toml` is written here, not copied: the human's model
 * settings and servers, then the worker's own approvals (auto-review, decision
 * 11), its trusted clone and runcastle's tools as its `worker` MCP server.
 */

/** What of the copy goes in a new start's place: cleared before each copy. The rollouts in `sessions/` stay, so a resume finds them. */
export const CODEX_SETUP_MANAGED = [
  '.codex/AGENTS.md',
  '.codex/skills',
  '.codex/prompts',
  '.codex/rules',
  '.codex/config.toml',
  '.codex/auth.json',
  '.codex/.credentials.json',
] as const

/** The folders of the human's Codex home copied whole when they have them. */
const CODEX_DIRS = ['skills', 'prompts', 'rules'] as const

/** The host files copied as they are: the Codex login, and the MCP logins Codex keeps in a file. */
const CODEX_LOGINS = ['auth.json', '.credentials.json'] as const

/**
 * The top-level keys of the human's `config.toml` a worker keeps: how the model
 * reasons and talks, and which provider serves it. Everything else (approvals,
 * sandbox, projects, notify, instruction files on host paths, profiles…) stays
 * on the host; the worker's model is its own.
 */
const CONFIG_KEPT = [
  'model_provider',
  'model_reasoning_effort',
  'model_reasoning_summary',
  'model_verbosity',
  'model_supports_reasoning_summaries',
  'model_context_window',
  'model_auto_compact_token_limit',
  'personality',
  'service_tier',
  'web_search',
] as const

/** The worker's own server; the human's of the same name, or runcastle's (unreachable from the sandbox), are left out. */
const OWN_SERVERS = ['worker', 'runcastle']

export interface CodexWorkerConfig {
  /** One of the human's annotated Codex models. */
  model: string
  /** The worker's briefing, after the human's own instructions. */
  briefing: string
  /** The worker's own MCP server, as `workerMcpServer` describes it. */
  mcp: { command: string; args: string[]; env: Record<string, string> }
}

const toml = (v: string): string => JSON.stringify(v)

function read(file: string): string | undefined {
  try {
    return readFileSync(file, 'utf8')
  } catch {
    return undefined
  }
}

/** The human's setup under `codexHome` (their `$CODEX_HOME`, else `~/.codex`), as a Codex worker's sandbox gets it. */
export function codexSetup(codexHome: string, worker: CodexWorkerConfig): CodexSetup {
  const files: SetupFile[] = []
  // Codex reads the override in place of AGENTS.md when it is there.
  const instructions = read(join(codexHome, 'AGENTS.override.md')) ?? read(join(codexHome, 'AGENTS.md'))
  files.push({ to: '.codex/AGENTS.md', content: instructions?.trim() ? `${instructions.trimEnd()}\n\n${worker.briefing}\n` : `${worker.briefing}\n` })
  for (const dir of CODEX_DIRS) {
    const from = join(codexHome, dir)
    if (existsSync(from) && statSync(from).isDirectory()) files.push({ to: `.codex/${dir}`, from })
  }
  for (const name of CODEX_LOGINS) {
    const from = join(codexHome, name)
    if (existsSync(from)) files.push({ to: `.codex/${name}`, from })
  }
  files.push({ to: '.codex/config.toml', content: workerCodexConfig(read(join(codexHome, 'config.toml')) ?? '', worker) })
  return { files }
}

/**
 * The worker's `config.toml`: the kept top-level keys and the `[mcp_servers…]`
 * and `[model_providers…]` tables of the human's config, lifted as text so no
 * field is lost, then the worker's own settings and server.
 */
export function workerCodexConfig(humanConfig: string, worker: CodexWorkerConfig): string {
  const { keys, tables } = liftedConfig(humanConfig)
  const env = Object.entries(worker.mcp.env)
    .map(([k, v]) => `${toml(k)} = ${toml(v)}`)
    .join(', ')
  return [
    '# Generated by runcastle for a worker — rewritten whenever the setup is copied in.',
    `model = ${toml(worker.model)}`,
    ...keys,
    // Auto-review (decision 11): Codex asks only for what its reviewer finds risky, and the reviewer answers.
    // codex-acp sends its session mode's approvals with every turn, so a session that reports another mode
    // (`workspace-write`: on-request, the human as reviewer) is the fallback, recorded as the worker's mode.
    'approval_policy = "on-request"',
    'approvals_reviewer = "auto_review"',
    'sandbox_mode = "workspace-write"',
    'check_for_update_on_startup = false',
    // No keyring in the sandbox: the MCP logins copied in are the file store's.
    'mcp_oauth_credentials_store = "file"',
    '',
    `[projects.${toml(IN.repo)}]`,
    'trust_level = "trusted"',
    '',
    // The human's tables first: TOML wants a parent table before its sub-tables.
    ...(tables ? [tables, ''] : []),
    '[mcp_servers.worker]',
    `command = ${toml(worker.mcp.command)}`,
    `args = [${worker.mcp.args.map(toml).join(', ')}]`,
    `env = { ${env} }`,
    // Runcastle's own tools never ask, under either reviewer.
    'default_tools_approval_mode = "approve"',
    '',
  ].join('\n')
}

/** The table path of a `[header]` or `[[header]]` line, quotes and spaces dropped around its parts. */
function tablePath(line: string): string | undefined {
  const header = /^\s*\[\[?([^\]]+)\]\]?\s*(#.*)?$/.exec(line)
  return header?.[1]?.split('.').map((part) => part.trim().replace(/^["']|["']$/g, '')).join('.')
}

function keptTable(path: string): boolean {
  if (path === 'model_providers' || path.startsWith('model_providers.')) return true
  if (path !== 'mcp_servers' && !path.startsWith('mcp_servers.')) return false
  const server = path.split('.')[1]
  return server === undefined || !OWN_SERVERS.includes(server)
}

/** The human's kept top-level key lines (a multi-line value stays with its key) and kept tables, as text. */
function liftedConfig(text: string): { keys: string[]; tables: string } {
  const keys: string[] = []
  const tables: string[] = []
  let table: string | undefined
  let keepKey = false
  for (const line of text.split(/\r?\n/)) {
    const path = tablePath(line)
    if (path !== undefined) table = path
    if (table === undefined) {
      const key = /^\s*([A-Za-z0-9_-]+)\s*=/.exec(line)?.[1]
      if (key) keepKey = (CONFIG_KEPT as readonly string[]).includes(key)
      else if (!line.trim() || line.trim().startsWith('#')) continue
      if (keepKey) keys.push(line)
    } else if (keptTable(table)) tables.push(line)
  }
  return { keys, tables: tables.join('\n').trim() }
}
